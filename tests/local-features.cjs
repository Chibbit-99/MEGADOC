// Optional Chromium regressions for local-only editing features; see README.
const assert = require('node:assert/strict');
const { chromium } = require('playwright-core');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ['--no-sandbox'] });
  const p = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; p.on('pageerror', e => errors.push(e.stack));
  const editor = p.locator('#page');
  try {
    await p.goto(process.env.MEGADOC_URL || 'http://localhost:8000');
    await p.locator('#emptyNewTab').click(); await p.locator('.tab-rename').press('Enter');
    await editor.click();
    await p.locator('[data-cmd=superscript]').click();
    assert.equal(await p.locator('[data-cmd=superscript]').getAttribute('aria-pressed'), 'true');
    await p.keyboard.type('2');
    assert.match(await editor.innerHTML(), /<sup>2<\/sup>/);
    await p.keyboard.press('Control+.');
    await p.keyboard.press('Control+,');
    await p.keyboard.type('3');
    assert.match(await editor.innerHTML(), /<sub>3<\/sub>/);
    await editor.evaluate(el => {
      el.innerHTML = '<h1>First</h1><p>text</p><h3>Second</h3>'; el.focus();
      const r = document.createRange(); r.selectNodeContents(el.querySelector('p')); r.collapse(true);
      const s = getSelection(); s.removeAllRanges(); s.addRange(r);
    });
    await p.keyboard.press('Control+Alt+Shift+ArrowDown');
    assert.equal(await p.evaluate(() => { const n=getSelection().anchorNode; return (n.nodeType===1 ? n : n.parentElement).closest('h1,h2,h3,h4,h5,h6')?.textContent; }), 'Second');
    await p.keyboard.press('Control+Alt+Shift+ArrowUp');
    assert.equal(await p.evaluate(() => { const n=getSelection().anchorNode; return (n.nodeType===1 ? n : n.parentElement).closest('h1,h2,h3,h4,h5,h6')?.textContent; }), 'First');
    await p.locator('#statusOutline').click();
    assert.equal(await p.locator('[data-heading]').count(), 2);
    await p.locator('[data-heading="1"]').click();
    assert.equal(await p.evaluate(() => { const n=getSelection().anchorNode; return (n.nodeType===1 ? n : n.parentElement).closest('h1,h2,h3,h4,h5,h6')?.textContent; }), 'Second');
    await p.keyboard.press('Control+Alt+2');
    assert.equal(await editor.locator('h2').count(), 1);
    await editor.evaluate(el => { el.focus(); const r=document.createRange(); r.selectNodeContents(el.querySelector('p')); r.collapse(false); const s=getSelection();s.removeAllRanges();s.addRange(r); document.dispatchEvent(new Event('selectionchange')); });
    await p.keyboard.press('Control+Shift+e');
    assert.equal(await editor.locator('p').evaluate(el=>getComputedStyle(el).textAlign), 'center');
    await p.keyboard.press('Control+Shift+7'); assert.equal(await editor.locator('ol').count(), 1);
    await p.keyboard.press('Control+Shift+7');
    await p.keyboard.press('Control+Shift+8'); assert.equal(await editor.locator('ul').count(), 1);
    await p.keyboard.press('Control+Shift+8');
    await p.locator('[data-menu="4"]').click();
    await p.locator('#menuDropdown .mi').filter({hasText:'Emoji & special'}).click();
    await p.locator('#symbolSearch').fill('U+2603');
    await p.locator('[data-symbol="☃"]').click();
    assert.match(await editor.innerText(), /☃/);
    await editor.evaluate(el => { el.innerHTML='<p>Cat <b>cat</b> cat.</p><p>cat + cat.</p><p>do<b>g</b>! [literal]</p>';el.dispatchEvent(new Event('input',{bubbles:true})); });
    await p.keyboard.press('Control+f');
    await p.locator('#findInput').fill('cat');
    assert.equal(await p.locator('#findCount').innerText(), '1 / 5');
    await p.locator('#findCase').check();
    assert.equal(await p.locator('#findCount').innerText(), '1 / 4');
    await p.locator('#replaceInput').fill('fox');
    await p.locator('#replaceAll').click();
    assert.match(await editor.innerText(), /Cat fox fox\./);
    assert.match(await editor.innerText(), /fox \+ fox\./);
    await p.locator('[data-cmd=undo]').click();
    assert.match(await editor.innerText(), /cat/);
    await p.locator('#findCase').uncheck();
    await p.locator('#findInput').fill('[literal]');
    assert.equal(await p.locator('#findCount').innerText(), '1 / 1');
    await p.locator('#findRegex').check(); await p.locator('#findInput').fill('[');
    assert.equal(await p.locator('#findCount').innerText(), 'Invalid regular expression');
    await p.locator('#findInput').fill('d.g');
    assert.equal(await p.locator('#findCount').innerText(), '1 / 1');
    await p.locator('#replaceInput').fill('wolf'); await p.locator('#replaceOne').click();
    assert.match(await editor.innerText(), /wolf!/);
    await p.locator('#findRegex').uncheck(); await p.locator('#findInput').fill('wolf');
    await p.locator('#replaceInput').fill(''); await p.locator('#replaceOne').click();
    assert.doesNotMatch(await editor.innerText(), /wolf/);
    // Matches must not span a non-text object and delete it during replacement.
    await editor.evaluate(el => { el.innerHTML='<p>a<img src="data:image/svg+xml,%3Csvg xmlns=%22http://www.w3.org/2000/svg%22 width=%222%22 height=%222%22/%3E">b<br>c</p>'; el.dispatchEvent(new Event('input',{bubbles:true})); });
    await p.locator('#findInput').fill('ab');
    assert.equal(await p.locator('#findCount').innerText(), 'No matches');
    await p.locator('#findInput').fill('bc');
    assert.equal(await p.locator('#findCount').innerText(), 'No matches');
    await p.locator('#replaceAll').click(); assert.equal(await editor.locator('img').count(),1);
    await p.locator('#findClose').click();
    await editor.evaluate(el => { el.innerHTML='<p><a href="https://example.com"><img src="data:image/svg+xml,%3Csvg xmlns=%22http://www.w3.org/2000/svg%22 width=%22200%22 height=%22100%22/%3E" width="200" height="100" alt="old" data-keep="yes"></a></p>';el.dispatchEvent(new Event('input',{bubbles:true})); });
    const img = editor.locator('img'); await img.evaluate(el=>el.decode()); await img.click(); await p.locator('#imageAlt').click();
    await p.locator('#imageDescription').fill('Snow & sea'); await p.locator('#imageTitle').fill('My title'); await p.locator('#mOk').click();
    assert.equal(await img.getAttribute('alt'),'Snow & sea'); assert.equal(await img.getAttribute('title'),'My title'); assert.equal(await img.getAttribute('data-keep'),'yes');
    assert.equal(await editor.locator('a img').count(),1);
    await p.locator('[data-cmd=undo]').click(); assert.equal(await img.getAttribute('alt'),'old');
    await p.locator('[data-cmd=redo]').click(); assert.equal(await img.getAttribute('alt'),'Snow & sea');
    await p.waitForTimeout(500); await p.reload(); assert.equal(await img.getAttribute('alt'),'Snow & sea');
    await img.click(); await p.locator('#imageLayoutButton').click();
    await p.locator('#imageLayout').selectOption('left'); await p.locator('#imageGap').fill('12'); await p.locator('#mOk').click();
    assert.equal(await img.evaluate(el=>getComputedStyle(el).float), 'left');
    assert.equal(await img.evaluate(el=>getComputedStyle(el).marginRight), '12px');
    assert.equal(await img.getAttribute('alt'),'Snow & sea'); assert.equal(await editor.locator('a img').count(), 1);
    await p.locator('[data-cmd=undo]').click(); assert.equal(await img.evaluate(el=>getComputedStyle(el).float), 'none');
    await p.locator('[data-cmd=redo]').click(); assert.equal(await img.evaluate(el=>getComputedStyle(el).float), 'left');
    await p.waitForTimeout(500); await p.reload(); assert.equal(await img.evaluate(el=>getComputedStyle(el).float), 'left');
    await img.click(); await p.locator('#imageLayoutButton').click(); await p.locator('#imageLayout').selectOption('right'); await p.locator('#mOk').click();
    assert.equal(await img.evaluate(el=>getComputedStyle(el).float), 'right');
    await img.click(); await p.locator('#imageLayoutButton').click(); await p.locator('#imageLayout').selectOption('break'); await p.locator('#mOk').click();
    assert.equal(await img.evaluate(el=>getComputedStyle(el).clear), 'both');
    await img.click(); await p.locator('#imageLayoutButton').click(); await p.locator('#imageLayout').selectOption('inline'); await p.locator('#mOk').click();
    assert.equal(await img.evaluate(el=>getComputedStyle(el).display), 'inline');
    assert.deepEqual(errors, []); console.log('Local feature checks passed');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode=1; });
